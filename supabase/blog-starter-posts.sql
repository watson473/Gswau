$t$A price increase is a business decision, not an apology. Here is how to plan it, announce it and keep the clients who value your work.$t$,
$t$Most barbers and stylists wait far too long to raise their prices. Rent goes up, products go up, your skill goes up, and your price stays where it was three years ago. A price increase is not greed. It is how you keep doing great work without burning out.

## Know when it is time

- Your book is full most weeks and new clients wait days for a slot.
- Your costs (rent, products, tools, education) have risen since your last increase.
- Your skill and results have clearly improved.
- You are working longer hours just to earn the same.

If two or more of these are true, it is time.

## Plan the number

Look at what you actually earn per hour after costs, not just the ticket price. Decide what you need to earn per hour, then work back to a price. Small, regular increases are easier for clients to accept than one big jump every few years.

## Give clients notice

Tell clients four to six weeks ahead. Put a short note at your station, in your booking page and in a message to regulars. Keep it simple and confident: what changes, when, and that you are grateful for their loyalty. Do not over-explain or apologise.

## Protect your best relationships

Some barbers keep the old price for a short time for long-standing clients, or for anyone who books their next visit before the new price starts. That rewards loyalty and fills your book at the same time.

## Expect a little turnover

A few price-sensitive clients may leave. That is normal, and it opens space for clients who value your work. Most clients stay when the service, the experience and the result are consistent.

