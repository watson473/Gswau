$t$Two common ways to work in a shop are booth rent and commission. Neither is better for everyone. The right choice depends on your clientele, your goals and how much of the business side you want to handle.

## How booth rent works

You pay the shop a fixed rent and keep what you earn. You usually set your own prices and hours, buy your own products and handle your own bookings, taxes and marketing.

- Best for: established professionals with a steady clientele.
- The risk: rent is due even in a slow week.

## How commission works

The shop pays you a percentage of the services you perform. The shop usually provides products, booking, marketing and often walk-in clients.

- Best for: professionals still building their clientele, or anyone who prefers to focus on the craft.
- The trade-off: you keep a smaller share of each service.

## Run the numbers both ways

Take an average month. Under booth rent, subtract your rent and every cost you would carry yourself. Under commission, work out your share. Compare the two honestly, including the time you would spend on admin.

## Think about the next step

Booth rent is often a step toward owning a shop, because it teaches you to run your own small business. Commission can be the right place to grow skills and clientele first.

