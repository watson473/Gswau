## What do ten years of barber wages actually show?

The U.S. Bureau of Labor Statistics publishes Occupational Employment and Wage Statistics for barbers, SOC 39-5011. Each row below is that May release, as printed. A release pools about three years of employer responses. The survey counts wage-and-salary workers. It leaves out the self-employed, and owners and partners in unincorporated firms. Commissions and tips are inside the wage. A self-employed booth renter is outside the count.

The dollar figure in parentheses is the annual median printed on that year's occupation page. BLS builds annual wages by multiplying the hourly figure by 2,080 hours. The May 2015, May 2024, and May 2025 news-release tables print the median hourly wage and the mean annual wage, and they do not print a separate annual median. Those three rows stay in the form the release printed.

- May 2015: 14,350 wage-and-salary barbers, median $11.95 an hour, mean annual wage $29,140.
- May 2016: 15,900 barbers, median $12.38 an hour ($25,760 a year), mean annual wage $29,900.
- May 2017: 18,810 barbers, median $12.33 an hour ($25,650 a year), mean annual wage $30,480.
- May 2018: 20,130 barbers, median $13.44 an hour ($27,960 a year), mean annual wage $33,220.
- May 2019: 20,030 barbers, median $14.50 an hour ($30,150 a year), mean annual wage $35,190.
- May 2020: 14,880 barbers, median $15.61 an hour ($32,470 a year), mean annual wage $38,050.
- May 2021: 12,910 barbers, median $14.41 an hour ($29,970 a year), mean annual wage $35,700.
- May 2022: 12,690 barbers, median $16.82 an hour ($34,990 a year), mean annual wage $39,350.
- May 2023: 15,990 barbers, median $17.38 an hour ($36,150 a year), mean annual wage $41,570.
- May 2024: 18,100 barbers, median $18.73 an hour, mean annual wage $47,800.
- May 2025: 15,000 barbers, median $18.37 an hour, mean annual wage $47,070.

Read the employment column as an estimate. In the May 2023 release its relative standard error was 17.7%. The published median hourly wage in the May 2015 release was $11.95. In the May 2025 release it was $18.37. The published mean annual wage moved from $29,140 to $47,070 over those same releases. On the May 2023 occupation page, the lowest-paid tenth of wage-and-salary barbers were at $26,770 and the highest-paid tenth were at $61,090. In May 2016 those edges were $18,210 and $47,400.

That spread is wage-and-salary pay. It is the public record of what employers reported. It is not a booth-rent ledger, and it is not a commission split.

## What does a commission barber actually take home?

On commission, the shop pays you a share of the services you do. The shop usually carries the chair, the product, the booking, and the walk-ins. Your paycheck moves with the book. A slow Tuesday pays less. A full Saturday pays more. You do not write a rent check when the week is empty.

No public survey with a sample and a date gives a ten-year series of barber commission splits. Software-company blogs quote ranges. Those pages do not show a sample, so they are not in the list above and they are not used as data here.

**Example, not survey data.** The calculator on this site starts at a $35 cut, 8 clients a day, 5 days a week, 48 weeks, and a 60% commission. Tips are off. That book is 1,920 services and $67,200 of service revenue.

- At a 60% keep, the example take-home is $40,320 for the year.
- At a 50% keep, the example take-home is $33,600 for the year.

The other 40%, or the other 50%, is the shop's cut of the service. Product, card fees, and tax sit outside this example, the same way they sit outside the calculator until you add them yourself.

## What does booth rent really cost over a year?

A ten-year public series of signed booth rents was not available. What is available is one dated snapshot of asking prices.

On 2 November 2026, Salon Renter pulled its live listings and kept the ones with a sane weekly price. Among listings with "Barber" in the title, the chair and booth rows (65 listings) had a median ask of $200 a week. The middle half asked $150 to $300 a week. The wider title group, 85 listings of every space type, landed on the same median and the same middle half. These are owner asking prices, not signed leases. Private suites in that pull sat higher, and the suite row with only nine listings is a small sample.

In the broader set, where the word barber appeared anywhere in the listing and the state had at least 15 priced listings, the median weekly ask was $227 in California, $200 in Florida, $200 in Texas, $185 in Illinois, and $188 in Georgia.

**Example, not survey data.** The calculator charges booth rent for all 52 weeks, including weeks you are not behind the chair. Applied to the snapshot:

- $150 a week is $7,800 for the year.
- $200 a week, the median ask in that pull, is $10,400 for the year.
- $250 a week is the calculator's default rent. It is not a figure from the snapshot. It is $13,000 for the year.
- $300 a week, the top of that middle half, is $15,600 for the year.

On the same $67,200 book, rent comes off the top and you keep the rest of the service money. Still an example, still before supplies and tax:

- $150 a week leaves $59,400.
- $200 a week leaves $56,800.
- $250 a week leaves $54,200.
- $300 a week leaves $51,600.

## Which barber made more?

**Example, not survey data.** On the full book of 8 clients a day, every chair from $150 to $300 a week left more service money than a 60% commission and more than a 50% commission. The $300 chair left $51,600. The 60% commission left $40,320. The 50% commission left $33,600.

Shrink the book to 4 clients a day and the same prices, and the year is 960 services and $33,600 of service revenue. A 60% commission leaves $20,160. A $300 chair leaves $18,000. Commission pays more on that thinner book.

The BLS mean annual wage of $47,070 in the May 2025 release is a third kind of number. It is employer-reported pay for wage-and-salary barbers, annualized at 2,080 hours, with commissions and tips inside it. It is not the winner of the example, and it is not a booth renter's profit.

## Who should rent, and who should stay on commission?

Stay on commission while the book is still under the break-even, and whenever you want the shop to carry product, booking, and the empty hours. The rent is due on a slow week either way. On commission, a slow week shrinks the check. On booth rent, the check to the shop stays the same size.

Rent the chair when your book is already past the break-even and you can cover a slow month, your own supplies, and your own tax without borrowing the rent. That is the barber the full-book example is describing. The thin-book example is the barber who should stay on commission until the book gets there.

The break-even in this example is the year's rent divided by the shop's cut on one service. Above that many services, the chair leaves more service money. Below it, commission does.

At $35 and a 60% keep, the shop's cut is $14 a service. A $200 week, the median ask in the November 2026 snapshot, is $10,400 a year, and the chair pulls ahead at 743 services. Across 48 weeks and 5 days, that is about 3 clients a day. A $300 week is $15,600 a year, and the chair pulls ahead at 1,115 services, just under 5 clients a day on that same schedule. At a 50% keep the shop's cut is $17.50, and the $200 chair pulls ahead at 595 services.

Put your own price, your own book, and your own rent into the calculator before you treat any of those lines as yours. The episode [Is It Time to Open Your Own Shop?](/podcast#episode-bdfdfa59-1f38-49dc-97cd-2e3eb623b411) takes the next step, from the chair to the whole shop. The book [Rent the Chair or Own the Shop](/library/rent-the-chair-or-own-the-shop) walks the same decision in long form.

